/**
 * One-shot builder: patches baseline save_* / delete_* bodies with log_audit_event calls.
 * Run: node scripts/build_desktop_audit_migration.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const baseline = fs.readFileSync(
  path.join('supabase/migrations/20260731143000_baseline_live_public.sql'),
  'utf8',
);

const targets = [
  'save_buyer',
  'save_department',
  'save_shift',
  'save_process_flow',
  'save_size_group',
  'save_resource',
  'save_style_order',
  'delete_style_order',
  'save_line_plan',
  'save_order_routing',
];

const entityByName = {
  save_buyer: 'buyer',
  save_department: 'department',
  save_shift: 'shift',
  save_process_flow: 'process_flow',
  save_size_group: 'size_group',
  save_resource: 'resource',
  save_style_order: 'style_order',
  delete_style_order: 'style_order',
  save_line_plan: 'line_plan',
  save_order_routing: 'order_routing',
};

const NL = '\\r?\\n';

function extractFunction(name) {
  const re = new RegExp(
    `CREATE OR REPLACE FUNCTION public\\.${name}\\([\\s\\S]*?\\$function\\$${NL}([\\s\\S]*?)${NL}\\$function\\$`,
    'm',
  );
  const m = baseline.match(re);
  if (!m) throw new Error(`Function not found: ${name}`);
  const block = m[0];
  const createCount = (block.match(/CREATE OR REPLACE FUNCTION/g) || []).length;
  if (createCount !== 1) {
    throw new Error(
      `${name}: expected 1 function block, got ${createCount} (check CRLF / baseline boundaries)`,
    );
  }
  return block;
}

function normalizeFunctionTerminator(fnSql) {
  // Closing delimiter only (end of block), not the opening "AS $function$".
  return fnSql.replace(/\n\$function\$\s*;?\s*$/m, '\n$function$;\n');
}

function patchBody(fnSql, entity, name) {
  let out = fnSql;

  if (name === 'delete_style_order') {
    return normalizeFunctionTerminator(
      out.replace(
        /(\s+DELETE FROM public\.style_orders\r?\n\s+WHERE id = p_order_id AND factory_id = p_factory_id;)/,
        `$1\n\n  PERFORM public.log_audit_event(p_factory_id, 'delete', 'style_order', p_order_id, '{}'::jsonb);`,
      ),
    );
  }

  if (name === 'save_style_order') {
    return normalizeFunctionTerminator(
      out.replace(
      /(\s+RETURN v_order_id;\s*\r?\nEND;)/,
        `\n  PERFORM public.log_audit_event(p_factory_id, CASE WHEN v_is_update THEN 'update' ELSE 'insert' END, '${entity}', v_order_id, '{}'::jsonb);\n$1`,
      ),
    );
  }

  if (name === 'save_line_plan') {
    return normalizeFunctionTerminator(
      out.replace(
      /(\s+END;\s*\r?\n\$function\$)/,
        `\n  PERFORM public.log_audit_event(p_factory_id, 'upsert', '${entity}', p_order_id, '{}'::jsonb);\n$1`,
      ),
    );
  }

  if (name === 'save_order_routing') {
    return normalizeFunctionTerminator(
      out.replace(
      /(\s+END;\s*\r?\n\$function\$)/,
        `\n  PERFORM public.log_audit_event(p_factory_id, 'upsert', '${entity}', p_order_id, jsonb_build_object('step_count', jsonb_array_length(COALESCE(p_steps, '[]'::jsonb))));\n$1`,
      ),
    );
  }

  out = out.replace(
    /(\s+DELETE FROM public\.[a-z_]+ [a-z0-9_]+ WHERE[\s\S]*?;\s*\r?\n)(\s+RETURN;)/,
    `$1    PERFORM public.log_audit_event(p_factory_id, 'delete', '${entity}', p_id, '{}'::jsonb);\n$2`,
  );

  out = out.replace(
    /(\r?\n)(\s+RETURN QUERY)/,
    `\n  PERFORM public.log_audit_event(p_factory_id, COALESCE(p_action, 'upsert'), '${entity}', v_id, '{}'::jsonb);\n$2`,
  );

  return normalizeFunctionTerminator(out);
}

const header = `-- Desktop audit coverage: wire log_audit_event into legacy write RPCs.
-- Generated by scripts/build_desktop_audit_migration.mjs — re-run after baseline changes.

`;

const supportDropdown = fs.readFileSync(
  path.join('supabase/migrations/20260731190000_save_support_dropdown_rpc.sql'),
  'utf8',
);

const supportPatched = supportDropdown
  .replace(
    /(\s+DELETE FROM public\.support_dropdowns sd[\s\S]*?;\s*\r?\n)(\s+RETURN;)/,
    `$1    PERFORM public.log_audit_event(p_factory_id, 'delete', 'support_dropdown', p_id, '{}'::jsonb);\n$2`,
  )
  .replace(
    /(\r?\n)(\s+RETURN QUERY\s+SELECT sd\.id)/,
    `\n  PERFORM public.log_audit_event(p_factory_id, p_action, 'support_dropdown', v_id, '{}'::jsonb);\n$2`,
  )
  .replace(/\nGRANT EXECUTE[\s\S]*$/m, '');
const supportPatchedNormalized = normalizeFunctionTerminator(supportPatched);

const ensureDefects = `-- ensure_department_defects
CREATE OR REPLACE FUNCTION public.ensure_department_defects(
  p_factory_id uuid, p_department_id uuid, p_default_defects jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_existing jsonb;
BEGIN
  IF p_factory_id IS NULL THEN RAISE EXCEPTION 'factory_id is required'; END IF;
  IF p_factory_id IS DISTINCT FROM public.current_factory_id() THEN RAISE EXCEPTION 'Factory mismatch'; END IF;
  IF NOT public.is_factory_admin() THEN RAISE EXCEPTION 'Not authorized'; END IF;
  IF p_department_id IS NULL THEN RAISE EXCEPTION 'department_id is required'; END IF;

  SELECT df.defects INTO v_existing
  FROM public.defects df
  WHERE df.department_id = p_department_id AND df.factory_id = p_factory_id
  LIMIT 1;

  IF v_existing IS NOT NULL THEN
    RETURN v_existing;
  END IF;

  IF p_default_defects IS NULL OR jsonb_typeof(p_default_defects) <> 'array' OR jsonb_array_length(p_default_defects) = 0 THEN
    RETURN '[]'::jsonb;
  END IF;

  INSERT INTO public.defects (factory_id, department_id, defects)
  VALUES (p_factory_id, p_department_id, p_default_defects);

  PERFORM public.log_audit_event(
    p_factory_id, 'insert', 'defects', p_department_id,
    jsonb_build_object('seed', true)
  );

  RETURN p_default_defects;
END;
$function$;

`;

const fulfillmentAudit = fs.readFileSync(
  path.join('supabase/migrations/20260808140000_audit_remediation_rls_rpc.sql'),
  'utf8',
);

function patchFulfillment(name) {
  const re = new RegExp(
    `CREATE OR REPLACE FUNCTION public\\.${name}\\([\\s\\S]*?\\$function\\$${NL}([\\s\\S]*?)${NL}END;\\s*${NL}\\$function\\$`,
    'm',
  );
  const m = fulfillmentAudit.match(re);
  if (!m) throw new Error(`Missing ${name}`);
  let block = m[0].replace(
    `CREATE OR REPLACE FUNCTION public.${name}`,
    `CREATE OR REPLACE FUNCTION public.${name}_inner`,
  );
  const entity = name === 'log_desktop_shipment' ? 'shipment' : 'rejection';
  block = block.replace(
    /(\s+RETURNING id INTO v_id;\s*\r?\n)/,
    `$1\n  PERFORM public.log_audit_event(p_factory_id, 'insert', '${entity}', v_id, COALESCE(p_payload, '{}'::jsonb));\n`,
  );
  return normalizeFunctionTerminator(block);
}

let out = header;
for (const name of targets) {
  out += patchBody(extractFunction(name), entityByName[name], name) + '\n\n';
}
out += supportPatchedNormalized + '\n\n';
out += ensureDefects + '\n';
out += patchFulfillment('log_desktop_shipment') + '\n\n';
out += patchFulfillment('log_desktop_rejection') + '\n';

const outPath = path.join(
  'supabase/migrations/20260810180000_desktop_audit_coverage.sql',
);
fs.writeFileSync(outPath, out, 'utf8');
process.stderr.write(`Wrote ${outPath} (${out.length} bytes)\n`);
